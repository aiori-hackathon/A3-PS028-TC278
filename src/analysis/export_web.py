"""Write the measured dataset into web/index.html (static page, no fetch, no build step).

    .venv/bin/python src/analysis/export_web.py            # rewrite web/index.html in place
    .venv/bin/python src/analysis/export_web.py --check    # print what would change, write nothing

Only the text between the HAPPYLAB DATA START/END markers is replaced. Inside it this writes:
  D[client][scenario]   = {med, win, ifd, runs:[used, target], src}
  WIN[client][scenario] = [IPv6 wins, IPv4 wins, no winner]
  IFDV[client][scenario]= [[run_id, inter-family delay ms], ...] for every used run that observed one;
                          [] when none did or the cell has no runs. Drawn as-is by the inter-family chart.
  RUNS                  = five representative runs for the Evidence page, each with the stored
                          record excerpt (rec, verbatim JSON text) and its check block (chk)
  CAPS                  = capture inventory: those five pcaps plus the two committed fixtures

Rules:
  - Records come only from the 14 sessions listed in docs/dataset.md.
  - A run whose cross_checks are not "agree" (or whose lab verify failed) is excluded from every
    aggregate and named in a warning; the exit status is then 1.
  - src: "val" (shown as "complete") = target runs used, all clean; "pil" = 1 to target-1; "ph" = none.
  - A cell with no usable runs keeps the placeholder values already in D (the page never draws them;
    it shows the cell as "not measured"), with src "ph" and runs [0, target]. Its WIN is [0, 0, 0]:
    no win split is carried for a cell nobody measured. No number is ever made up here.
  - win is the modal winner among IPv6/IPv4; a tie has no mode, is reported, and exits 1.
  - ifd is null when no run observed an inter-family delay (never 0); otherwise the median of the
    observed values only.
  - The penalty is not exported: the page computes it from each client's own C0 median.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import statistics
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from analysis.summarise import (  # noqa: E402
    DATASET_DOC, EXPECTED_REPS, REPO, RUNS_DIR, Run, dataset_sessions, run_from_record)

PAGE = REPO / "web" / "index.html"
FIXTURES = REPO / "src" / "tests" / "fixtures"
START = "/* === HAPPYLAB DATA START — generated by export_web.py, do not edit by hand === */\n"
END = "/* === HAPPYLAB DATA END === */\n"
CLIENT_ORDER = ("curl", "chromium")
# (scenario, client): the Evidence page's five runs, each the run nearest its cell's median setup.
# The second one is the page's default selection (showRun(RUNS[1])).
REPRESENTATIVE = (("C0", "curl"), ("S1", "curl"), ("S1", "chromium"), ("S4", "chromium"), ("S6", "curl"))
FIXTURE_CAPS = (
    ("s1_manual_curl.pcap", "S1", "curl", "pinned fixture · hand-checked"),
    ("loopback_two_harness_runs.pcap", "—", "curl", "pinned fixture · loopback harness, not lab data"),
)


class ExportError(Exception):
    pass


# --- the page's existing block ------------------------------------------------------------

def split_page(text: str) -> tuple[str, str, str]:
    """(before, block, after); refuses a page without exactly one START ... END pair."""
    if text.count(START) != 1 or text.count(END) != 1:
        raise ExportError("web/index.html must contain the HAPPYLAB DATA START and END markers exactly once each")
    a = text.index(START) + len(START)
    b = text.index(END)
    if b < a:
        raise ExportError("HAPPYLAB DATA END comes before START")
    return text[:a], text[a:b], text[b:]


_D_CELL = re.compile(r'(\w+):\{med:([-\d.]+),win:"(v[46])",ifd:(null|[-\d.]+),runs:\[(\d+),(\d+)\],src:"(\w+)"\}')
_WIN_CELL = re.compile(r"(\w+):\[(\d+),(\d+),(\d+)\]")


def _client_sections(block: str, var: str) -> dict[str, str]:
    try:
        body = block[block.index(f"var {var}="):]
    except ValueError as exc:
        raise ExportError(f"no var {var} in the page's data block") from exc
    out = {}
    for c in CLIENT_ORDER:
        m = re.search(rf"\b{c}:\{{", body)
        if not m:
            raise ExportError(f"cannot find {var}.{c} in the page's data block")
        depth, i = 1, m.end()
        while depth:
            if i >= len(body):
                raise ExportError(f"unbalanced braces in {var}.{c}")
            depth += {"{": 1, "}": -1}.get(body[i], 0)
            i += 1
        out[c] = body[m.end():i - 1]
    return out


def parse_existing(block: str) -> tuple[dict, dict]:
    """The page's current D and WIN, used only for cells that keep their placeholder values."""
    d = {c: {sid: {"med": float(med), "win": win, "ifd": None if ifd == "null" else float(ifd),
                   "runs": [int(r0), int(r1)], "src": src}
             for sid, med, win, ifd, r0, r1, src in _D_CELL.findall(sec)}
         for c, sec in _client_sections(block, "D").items()}
    w = {c: {sid: [int(a), int(b), int(n)] for sid, a, b, n in _WIN_CELL.findall(sec)}
         for c, sec in _client_sections(block, "WIN").items()}
    for c in CLIENT_ORDER:
        if not d[c] or set(d[c]) != set(w[c]):
            raise ExportError(f"D.{c} and WIN.{c} in the page do not list the same scenarios")
    return d, w


# --- records -------------------------------------------------------------------------------

@dataclass
class Cell:
    used: list[tuple[Run, dict]] = field(default_factory=list)   # (run, record)
    excluded: list[tuple[str, str]] = field(default_factory=list)  # (run_id, reason)


def problem(rec: dict) -> str | None:
    cc = rec.get("cross_checks", {})
    if cc.get("status") != "agree":
        fields = ", ".join(c.get("field", "?") for c in cc.get("conflicts", [])) or "no detail"
        return f"cross_checks {cc.get('status')}: {fields}"
    ev = rec.get("evidence", {})
    if not (ev.get("pre_verify_ok") is True and ev.get("post_restore_verify_ok") is True):
        return "lab verify did not pass before and after the run"
    return None


def load_cells(sessions: list[tuple[str, str, str]], runs_dir: Path = RUNS_DIR) -> dict[tuple[str, str], Cell]:
    by_session: dict[str, list[dict]] = {}
    for p in sorted(runs_dir.glob("*.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        by_session.setdefault(r.get("environment", {}).get("session_id"), []).append(r)
    cells: dict[tuple[str, str], Cell] = {}
    for client, scenario, sid in sessions:
        cell = cells.setdefault((client, scenario), Cell())
        for r in sorted(by_session.get(sid, []), key=lambda r: r["scenario"]["repetition"]):
            if (r["client"]["name"], r["scenario"]["id"]) != (client, scenario):
                cell.excluded.append((r["run_id"], f"is {r['client']['name']}/{r['scenario']['id']}, "
                                                   f"not {client}/{scenario}"))
                continue
            why = problem(r)
            if why:
                cell.excluded.append((r["run_id"], why))
            else:
                cell.used.append((run_from_record(r), r))
    return cells


# --- aggregates ----------------------------------------------------------------------------

def modal_winner(runs: list[Run]) -> str | None:
    """'v6' or 'v4' by count among runs that had a winner; None when there is no single mode."""
    n = Counter(r.winner for r in runs if r.winner in ("v6", "v4"))
    if not n:
        return None
    (top, a), *rest = n.most_common()
    if rest and rest[0][1] == a:
        return None
    return top


def win_counts(runs: list[Run]) -> list[int]:
    return [sum(r.winner == "v6" for r in runs), sum(r.winner == "v4" for r in runs),
            sum(r.winner not in ("v6", "v4") for r in runs)]


def src_for(used: int, target: int) -> str:
    return "val" if used >= target else "pil" if used > 0 else "ph"


def r3(x: float) -> float:
    return round(x, 3)


def build_cell(runs: list[Run], target: int, placeholder: dict, label: str, warn) -> tuple[dict, list[int], bool]:
    """(D cell, WIN cell, ok). ok is False when the cell needs a person (tie, used > target)."""
    setups = [r.setup_ms for r in runs if r.setup_ms is not None]
    if not runs or not setups:
        if runs:
            warn(f"{label}: {len(runs)} usable runs but none has a TCP setup time; keeping the placeholder")
        return {**placeholder, "runs": [0, target], "src": "ph"}, [0, 0, 0], True
    ok = True
    win = modal_winner(runs)
    if win is None:
        warn(f"{label}: no single modal winner {win_counts(runs)}; cell needs a decision")
        ok = False
        win = placeholder["win"]
    observed = [r.inter_family_ms for r in runs if r.inter_family_ms is not None]
    if observed and len(observed) < len(runs):
        warn(f"{label}: inter-family delay observed in {len(observed)} of {len(runs)} runs; "
             "ifd is the median of the observed runs only")
    if len(runs) > target:
        warn(f"{label}: {len(runs)} usable runs, more than the target {target}")
        ok = False
    cell = {"med": r3(statistics.median(setups)), "win": win,
            "ifd": r3(statistics.median(observed)) if observed else None,
            "runs": [len(runs), target], "src": src_for(len(runs), target)}
    return cell, win_counts(runs), ok


# --- Evidence page -------------------------------------------------------------------------

def record_excerpt(rec: dict) -> dict:
    """Stored fields, verbatim, for the Evidence page's 'Stored record' panel."""
    return {
        "schema_version": rec["schema_version"],
        "run_id": rec["run_id"],
        "scenario": {"id": rec["scenario"]["id"], "repetition": rec["scenario"]["repetition"]},
        "client": {"name": rec["client"]["name"], "version": rec["client"].get("version")},
        "packet_observations": rec["packet_observations"],
        "metrics": rec["metrics"],
        "outcome": {k: rec["outcome"].get(k) for k in ("success", "http_status", "exit_code", "source")},
        "evidence": {k: rec["evidence"].get(k) for k in ("pcap_path", "pcap_sha256", "pre_verify_ok",
                                                          "post_restore_verify_ok")},
        "cross_checks": rec["cross_checks"],
    }


def representative(cell: Cell) -> tuple[Run, dict] | None:
    pts = [(run, rec) for run, rec in cell.used if run.setup_ms is not None]
    if not pts:
        return None
    med = statistics.median(run.setup_ms for run, _ in pts)
    return min(pts, key=lambda p: (abs(p[0].setup_ms - med), p[0].repetition))


def run_entry(run: Run, rec: dict, src: str) -> dict:
    return {
        "id": run.run_id, "sc": run.scenario, "cl": run.client, "src": src,
        "setup": r3(run.setup_ms), "ifd": None if run.inter_family_ms is None else r3(run.inter_family_ms),
        "win": {"v6": "ipv6", "v4": "ipv4"}.get(run.winner, "none"),
        "ab": run.failed_or_abandoned if run.failed_or_abandoned is not None else 0,
        "dns": r3(run.dns_ms) if run.dns_ms is not None else None,
        "out": "success" if run.success else "failure",
        "rec": json.dumps(record_excerpt(rec), indent=2, ensure_ascii=False),
        "chk": {"status": rec["cross_checks"]["status"], "conflicts": rec["cross_checks"]["conflicts"],
                "pre": rec["evidence"].get("pre_verify_ok"), "post": rec["evidence"].get("post_restore_verify_ok"),
                "sha": rec["evidence"].get("pcap_sha256"), "path": f"data/generated/runs/{rec['run_id']}.json"},
    }


def short_sha(h: str) -> str:
    return f"{h[:4]}…{h[-4:]}"


def size_text(n: int) -> str:
    return f"{n} B" if n < 1024 else f"{round(n / 1024):,} KB"


def cap_row(path: Path, scenario: str, client: str, role: str, sha: str | None = None) -> list[str]:
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if sha is not None and digest != sha:
        raise ExportError(f"{path}: sha256 does not match the record")
    return [path.name, scenario, client, size_text(len(data)), short_sha(digest), role]


# --- output --------------------------------------------------------------------------------

def js(x) -> str:
    return json.dumps(x, ensure_ascii=False)


def ifd_values(runs: list[Run]) -> list[list]:
    """[[run_id, value], ...] for runs where the inter-family delay was observed, in run order."""
    return [[r.run_id, r3(r.inter_family_ms)] for r in sorted(runs, key=lambda r: r.repetition)
            if r.inter_family_ms is not None]


def render_block(d: dict, win: dict, runs: list[dict], caps: list[list[str]], header: str,
                 ifdv: dict | None = None) -> str:
    scen = list(next(iter(d.values())).keys())
    out = [f"/* {header} */",
           "/* med = median setup ms · win = winning family · ifd = inter-family delay median (null = not observed)",
           "   runs = completed/target · src = provenance key */",
           "var D={"]
    for i, c in enumerate(CLIENT_ORDER):
        out.append(f"  {c}:{{")
        for j, s in enumerate(scen):
            x = d[c][s]
            out.append(f'    {s}:{{med:{x["med"]},win:"{x["win"]}",ifd:{"null" if x["ifd"] is None else x["ifd"]},'
                       f'runs:[{x["runs"][0]},{x["runs"][1]}],src:"{x["src"]}"}}' + ("," if j < len(scen) - 1 else ""))
        out.append("  }" + ("," if i < len(CLIENT_ORDER) - 1 else ""))
    out.append("};")
    out.append("var WIN={ /* repetitions won by each family: [IPv6, IPv4, no winner] */")
    for i, c in enumerate(CLIENT_ORDER):
        cells = ",".join(f"{s}:[{w[0]},{w[1]},{w[2]}]" for s in scen for w in [win[c][s]])
        out.append(f"  {c}:{{{cells}}}" + ("," if i < len(CLIENT_ORDER) - 1 else ""))
    out.append("};")
    out.append("var IFDV={ /* observed inter-family delays per run: [run_id, ms]; [] = none observed or no runs */")
    for i, c in enumerate(CLIENT_ORDER):
        out.append(f"  {c}:{{")
        for j, s in enumerate(scen):
            vals = (ifdv or {}).get(c, {}).get(s, [])
            out.append(f"    {s}:[" + ",".join(f"[{js(rid)},{v}]" for rid, v in vals) + "]"
                       + ("," if j < len(scen) - 1 else ""))
        out.append("  }" + ("," if i < len(CLIENT_ORDER) - 1 else ""))
    out.append("};")
    out.append("var RUNS=[")
    keys = ("id", "sc", "cl", "src", "setup", "ifd", "win", "ab", "dns", "out", "rec", "chk")
    for i, r in enumerate(runs):
        out.append("  {" + ",".join(f"{k}:{js(r[k])}" for k in keys) + "}" + ("," if i < len(runs) - 1 else ""))
    out.append("];")
    out.append("var CAPS=[")
    for i, c in enumerate(caps):
        out.append("  " + js(c) + ("," if i < len(caps) - 1 else ""))
    out.append("];")
    return "\n".join(out) + "\n"


@dataclass
class Export:
    block: str
    warnings: list[str]
    ok: bool


def export(page_text: str, sessions: list[tuple[str, str, str]], runs_dir: Path = RUNS_DIR,
           repo: Path = REPO, target: int = EXPECTED_REPS, fixtures: Path = FIXTURES) -> Export:
    _, block, _ = split_page(page_text)
    old_d, _ = parse_existing(block)  # WIN is parsed only to check it matches D
    cells = load_cells(sessions, runs_dir)
    warnings: list[str] = []
    ok = True
    d: dict = {c: {} for c in CLIENT_ORDER}
    win: dict = {c: {} for c in CLIENT_ORDER}
    ifdv: dict = {c: {} for c in CLIENT_ORDER}
    for c in CLIENT_ORDER:
        for s in old_d[c]:
            cell = cells.get((c, s), Cell())
            for run_id, why in cell.excluded:
                warnings.append(f"excluded {run_id} ({why})")
                ok = False
            d[c][s], win[c][s], cell_ok = build_cell([run for run, _ in cell.used], target, old_d[c][s],
                                                     f"{c}/{s}", warnings.append)
            ok &= cell_ok
            ifdv[c][s] = ifd_values([run for run, _ in cell.used])
    for (c, s) in cells:
        if s not in old_d[c]:
            raise ExportError(f"dataset has {c}/{s} but the page has no such scenario")

    runs, caps = [], []
    for s, c in REPRESENTATIVE:
        pick = representative(cells.get((c, s), Cell()))
        if pick is None:
            warnings.append(f"no representative run for {c}/{s}; Evidence page left without it")
            continue
        run, rec = pick
        runs.append(run_entry(run, rec, d[c][s]["src"]))
        caps.append(cap_row(repo / rec["evidence"]["pcap_path"], s, c, "dataset run", rec["evidence"]["pcap_sha256"]))
    caps += [cap_row(fixtures / name, s, c, role) for name, s, c, role in FIXTURE_CAPS]

    codes = sorted({rec["environment"].get("git_commit", "?") for cell in cells.values() for _, rec in cell.used})
    dates = sorted({rec["timestamps"]["run_start_utc"][:10] for cell in cells.values() for _, rec in cell.used})
    used = sum(len(cell.used) for cell in cells.values())
    header = (f"{used} runs from the {len(sessions)} sessions in docs/dataset.md; "
              f"runs dated {', '.join(dates) or '-'}; code {', '.join(codes) or '-'}")
    return Export(render_block(d, win, runs, caps, header, ifdv), warnings, ok)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--page", type=Path, default=PAGE)
    ap.add_argument("--check", action="store_true", help="report only; do not write the page")
    a = ap.parse_args(argv)
    try:
        text = a.page.read_text(encoding="utf-8")
        res = export(text, dataset_sessions(DATASET_DOC))
    except Exception as exc:  # noqa: BLE001 — every failure is reported and exits non-zero
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    for w in res.warnings:
        print(f"WARNING: {w}", file=sys.stderr)
    before, old, after = split_page(text)
    if old == res.block:
        print(f"{a.page}: data block already up to date")
    elif a.check:
        print(f"{a.page}: data block would change (--check, nothing written)")
    else:
        a.page.write_text(before + res.block + after, encoding="utf-8")
        print(f"{a.page}: data block rewritten")
    return 0 if res.ok else 1


if __name__ == "__main__":
    sys.exit(main())
