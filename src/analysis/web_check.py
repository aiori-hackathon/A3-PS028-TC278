"""Consistency check for web/index.html: the page against the report, the findings docs and the deck.

    env -u PYTHONPATH .venv/bin/python src/analysis/web_check.py      # exit 1 and list every problem

Needs no lab data: it reads only the committed page, docs/, deck/deck_numbers.json, web/figures/ and
docs/figures/. export_web.py runs it after every export and with --check, and
src/tests/test_web_check.py runs it in scripts/test.sh.

It fails when any of these diverge:
  1. Deck numbers. Every value in the Extensions block's N (keyed like deck_numbers.json) equals the
     deck's text; the core block's medians and inter-family delays equal the deck's core numbers;
     each extension dataset's run count and the 1,328-run total equal the deck's.
  2. Every other number. Each number in the page's own text (every section except the Playground,
     whose figures are model settings, and outside scripts, styles and drawings) and in the generated
     Extensions block appears verbatim in docs/report.md or deck/deck_numbers.json, or in a doc that
     docs/report.md itself links as its source (its findings docs and dataset manifests; the list is
     read from the report, so it follows the report). The one other source is a single stored run:
     a number that is a value in the generated REPLAY block, which export_web reads from the committed
     examples/ records after checking each capture's SHA-256. README.md is not a source. RFC numbers
     are names, not values, and are skipped. Only numbers with a decimal point or three or more
     digits are checked: small counts such as "20 runs" match almost anywhere.
  3. Evidence tags. The Extensions block carries the dashboard's four tags verbatim, and every
     data-tag on the page names one of them.
  4. Wording. The Extensions page says the he sweep "tracks", the crossovers "reproduce" published
     work, and the jitter model was not a prediction registered before the data; it never uses the
     banned phrasings below, and uses British spelling.
  5. Figures. Every figures/<name>.svg the page uses is in web/figures/ and byte-identical to
     docs/figures/<name>.svg, and web/figures/ holds nothing else.
  6. Offline. No stylesheet, script, image, frame or font is loaded from another host.
"""

from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PAGE = REPO / "web" / "index.html"
WEB_FIGURES = REPO / "web" / "figures"
DOC_FIGURES = REPO / "docs" / "figures"
DECK_NUMBERS = REPO / "deck" / "deck_numbers.json"

CORE_START = "/* === HAPPYLAB DATA START — generated by export_web.py, do not edit by hand === */\n"
CORE_END = "/* === HAPPYLAB DATA END === */\n"
EXT_START = ("/* === HAPPYLAB EXTENSIONS START — generated by export_web.py from the certified extension "
             "datasets and examples/, do not edit by hand === */\n")
EXT_END = "/* === HAPPYLAB EXTENSIONS END === */\n"

TAG_LABEL = {"packet": "Packet-level (pcap)", "client": "Client log", "interp": "Interpretation",
             "derived": "Derived (pcap − lab RTT)"}   # src/tests/test_web_check.py pins this to dashboard.TAG_LABEL

# deck key -> (client, scenario, field) in the core block's D
CORE_DECK = {f"{p}_{s}": (c, s, "med") for c, p in (("curl", "curl"), ("chromium", "chr"))
             for s in ("C0", "S1", "S2", "S3", "S4", "S5", "S6")}
CORE_DECK |= {"curl_ifd_S1": ("curl", "S1", "ifd"), "chr_ifd_S1": ("chromium", "S1", "ifd")}
DATASET_DECK = {"latency-sweep": "ls_runs", "he-sweep": "he_runs", "jitter-loss": "jl_runs"}

REQUIRED = (
    ("tracks", "the he sweep: T minus the handshake tracks the timeout"),
    ("reproduce", "the crossovers reproduce the published values"),
    ("not a prediction registered before", "the jitter model was not registered before the data"),
)
BANNED = (
    (r"predicted before the data|pre-registered|preregistered", "the jitter model was not predicted before the data"),
    (r"\bequals?\b|\bequal to\b", "the he sweep tracks the timeout; it does not equal it"),
    (r"\bdiscover", "the crossovers reproduce published work; they are not a discovery"),
    (r"\bconform", "no conformance claims"),
    (r"\bimplement(s|ed|ation|ations)?\b|\btimer value|\binternal timer", "no claims about client internals"),
    (r"RFC 8305 predicts|\bpredicted by RFC", "RFC 8305 is a reference, not a predictor"),
    (r"\b(behavior|color|colors|analyze|analyzed|center|favor|optimize)\b", "British spelling"),
    # Not measured here. The kernel docs give about 131 s for tcp_syn_retries=6 with
    # tcp_syn_linear_timeouts=4; no run reached it, so the page says "many seconds".
    (r"tens of seconds|\b1[23]\d\s*(?:s|sec|seconds)\b|~\s*1[23]\d\b", "connect timeout: say \"many seconds\""),
    (r"\beliminat\w*|\bprove[sn]?\b|removes that wait", "Happy Eyeballs bounds the wait; the page shows packets, it does not prove"),
)
NUM = re.compile(r"(?<![\w.,])[−+-]?(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?")


# --- reading the page ----------------------------------------------------------------------

def block(text: str, start: str, end: str) -> str:
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError(f"the page must contain {start.strip()[:40]}… and its END marker exactly once each")
    a, b = text.index(start) + len(start), text.index(end)
    if b < a:
        raise ValueError("an END marker comes before its START")
    return text[a:b]


def js_var(blk: str, name: str):
    """var NAME=<json>; written by export_web.render_extensions (one line, plain JSON)."""
    m = re.search(rf"^var {name}=(.*);$", blk, re.MULTILINE)
    if not m:
        raise ValueError(f"no var {name} in the Extensions block")
    return json.loads(m.group(1))


def core_values(blk: str) -> dict:
    out = {}
    for c in ("curl", "chromium"):
        m = re.search(rf"\b{c}:\{{(.*?)\n  \}}", blk[blk.index("var D="):], re.DOTALL)
        for sid, med, ifd in re.findall(r"(\w+):\{med:(null|[-\d.]+),win:[^,]+,ifd:(null|[-\d.]+)", m.group(1)):
            out[(c, sid)] = {"med": None if med == "null" else float(med), "ifd": None if ifd == "null" else float(ifd)}
    return out


def section(text: str, sid: str) -> str:
    m = re.search(rf'<section id="{sid}"[^>]*>(.*?)</section>', text, re.DOTALL)
    if not m:
        raise ValueError(f"no <section id={sid!r}> on the page")
    return m.group(1)


def visible_text(fragment: str) -> str:
    """Text a reader sees, without scripts, styles and inline drawings."""
    fragment = re.sub(r"<(script|style|svg)\b.*?</\1>", " ", fragment, flags=re.DOTALL | re.IGNORECASE)
    fragment = re.sub(r"<[^>]+>", " ", fragment)
    return html.unescape(fragment)


def page_text(text: str) -> str:
    """Every section's text and the top of the page, less the Playground (model figures, not data)."""
    body = text.split("<body>", 1)[-1]
    body = re.sub(r"<script\b.*?</script>", " ", body, flags=re.DOTALL)
    body = re.sub(r'<section id="p-playground".*?</section>', " ", body, flags=re.DOTALL)
    return visible_text(body)


def strings(x) -> list[str]:
    if isinstance(x, str):
        return [x]
    if isinstance(x, dict):
        return [s for v in x.values() for s in strings(v)]
    if isinstance(x, list):
        return [s for v in x for s in strings(v)]
    return []


def number_sources(repo: Path = REPO) -> list[Path]:
    """docs/report.md, deck/deck_numbers.json and the docs the report links as its sources."""
    report = repo / "docs" / "report.md"
    linked = sorted({(report.parent / m).resolve() for m in
                     re.findall(r"\]\(([\w./-]+\.md)(?:#[^)]*)?\)", report.read_text(encoding="utf-8"))})
    return [report, repo / "deck" / "deck_numbers.json", *[p for p in linked if p.is_file()]]


def corpus(repo: Path = REPO) -> str:
    return "\n".join(p.read_text(encoding="utf-8") for p in number_sources(repo))


def replay_numbers(rep: list) -> set[str]:
    """Every number in the stored example runs, as the page could print it (3 decimals as stored)."""
    out: set[str] = set()

    def walk(x):
        if isinstance(x, bool) or x is None:
            return
        if isinstance(x, (int, float)):
            out.update({str(x), f"{x:.3f}"})
        elif isinstance(x, str):
            out.update(checked_numbers(x))
        elif isinstance(x, dict):
            [walk(v) for v in x.values()]
        elif isinstance(x, list):
            [walk(v) for v in x]
    walk(rep)
    return out


def checked_numbers(text: str) -> list[str]:
    """Numbers worth checking: a decimal point or three or more digits. RFC numbers are names, not values."""
    out = []
    for tok in NUM.findall(re.sub(r"\bRFC \d+", " ", text)):
        digits = re.sub(r"\D", "", tok)
        if "." in tok or len(digits) >= 3:
            out.append(tok.lstrip("+"))
    return out


# --- the check -----------------------------------------------------------------------------

def check_page(text: str, repo: Path = REPO) -> list[str]:
    problems: list[str] = []
    deck = {k: v["text"] for k, v in json.loads((repo / "deck" / "deck_numbers.json").read_text(encoding="utf-8")).items()
            if not k.startswith("_")}
    scale = json.loads((repo / "deck" / "deck_numbers.json").read_text(encoding="utf-8"))["_scale"]
    try:
        core = core_values(block(text, CORE_START, CORE_END))
        ext_blk = block(text, EXT_START, EXT_END)
        ext, rep = js_var(ext_blk, "EXT"), js_var(ext_blk, "REPLAY")
    except (ValueError, AttributeError, json.JSONDecodeError) as exc:
        return [f"cannot read the generated blocks: {exc}"]

    # 1. deck numbers
    for k, v in ext["N"].items():
        if k not in deck:
            problems.append(f"Extensions number {k} = {v!r} has no entry in deck_numbers.json")
        elif deck[k].strip("| ") != v:
            problems.append(f"{k}: page {v!r}, deck {deck[k]!r}")
    for k, (c, s, f) in CORE_DECK.items():
        v = core.get((c, s), {}).get(f)
        if v is None or f"{v:.3f}".rstrip("0") != deck[k].rstrip("0"):
            problems.append(f"{k}: core block {c}/{s} {f} = {v}, deck {deck[k]!r}")
    for k, shown in re.findall(r'data-deck="(\w+)"[^>]*>([^<]*)<', text):
        if k not in deck:
            problems.append(f'data-deck="{k}" has no entry in deck_numbers.json')
        elif html.unescape(shown).strip() != deck[k]:
            problems.append(f"{k}: page {shown!r}, deck {deck[k]!r}")
    for ds in ext["datasets"]:
        k = DATASET_DECK.get(ds["name"])
        if k and deck[k] != f"{ds['runs']} runs":
            problems.append(f"{k}: page {ds['runs']} runs, deck {deck[k]!r}")
    if f"{ext['runs']['total']:,} runs" not in scale or f"core {ext['runs']['core']}" not in scale:
        problems.append(f"run total {ext['runs']['total']:,} (core {ext['runs']['core']}) does not match the deck: {scale!r}")
    if len(ext["datasets"]) != 4:
        problems.append(f"the page lists {len(ext['datasets'])} extension datasets, not four")

    # 2. every other number
    known = corpus(repo).replace("−", "-")
    runs = replay_numbers(rep)
    seen = page_text(text) + "\n" + "\n".join(strings({k: v for k, v in ext.items() if k != "tags"}))
    for tok in sorted(set(checked_numbers(seen))):
        if tok.replace("−", "-") not in known and tok not in runs:
            problems.append(f"number {tok} on the page appears in neither docs/report.md (with the docs it links) "
                            "nor deck_numbers.json, and is not a value of a stored example run")

    # 3. evidence tags
    if ext["tags"] != TAG_LABEL:
        problems.append(f"Extensions tags {ext['tags']} differ from the dashboard's {TAG_LABEL}")
    markup = re.sub(r"<script\b.*?</script>", " ", text, flags=re.DOTALL)
    for t in sorted(set(re.findall(r'data-tag="([^"]*)"', markup))):
        if t not in TAG_LABEL:
            problems.append(f'data-tag="{t}" is not one of the four evidence tags')

    # 4. wording on the Extensions page
    ext_html = section(text, "p-extensions")
    ext_text = " ".join(visible_text(ext_html).split())
    # a cited title is someone else's wording, not a claim of ours: left out of the banned-phrase scan
    ext_claims_text = " ".join(visible_text(re.sub(r"<cite>.*?</cite>", " ", ext_html, flags=re.DOTALL)).split())
    claims = " ".join(c["claim"] for c in ext["claims"])
    for phrase, why in REQUIRED:
        if phrase not in ext_text:
            problems.append(f"the Extensions page must say {phrase!r} ({why})")
    # every page but the Playground's model, and the Playground's own wording in its script
    whole = " ".join(page_text(re.sub(r"<cite>.*?</cite>", " ", text, flags=re.DOTALL)).split())
    pg_js = text.split("/* ===================== playground", 1)[-1]
    pg_script = " ".join(a or b for a, b in re.findall(r'"([^"]*)"|\'([^\']*)\'', pg_js))
    for pat, why in BANNED:
        for where, t in (("page", whole), ("Playground text", pg_script),
                         ("Extensions page", ext_claims_text), ("claims table", claims), ("replays", " ".join(strings(rep)))):
            if where == "Playground text" and why == "British spelling":
                continue   # script strings hold CSS and API names (color:, behavior:); spelling is checked on visible text
            for m in re.finditer(pat, t, re.IGNORECASE):
                problems.append(f"{where}: {m.group(0)!r} ({why}): …{t[max(0, m.start() - 50):m.end() + 50]}…")

    # 5. figures
    used = sorted(set(re.findall(r"figures/([\w-]+\.svg)", text)))
    for name in used:
        web, doc = repo / "web" / "figures" / name, repo / "docs" / "figures" / name
        if not doc.is_file():
            problems.append(f"figures/{name} is not a figure in docs/figures/")
        elif not web.is_file() or web.read_bytes() != doc.read_bytes():
            problems.append(f"web/figures/{name} is missing or differs from docs/figures/{name} (run export_web.py)")
    extra = sorted({p.name for p in (repo / "web" / "figures").glob("*")} - set(used)) if (repo / "web" / "figures").is_dir() else []
    if extra:
        problems.append(f"web/figures/ holds files the page does not use: {extra}")

    # 6. offline
    for m in re.finditer(r"<(link|script|img|source|iframe|video|audio|embed|object)\b[^>]*?"
                         r"\b(href|src|srcset|data)\s*=\s*[\"']?(?:https?:)?//", text, re.IGNORECASE):
        problems.append(f"external request: {text[m.start():m.end() + 60]!r}")
    for m in re.finditer(r"@import|url\(\s*[\"']?(?:https?:)?//|\bfetch\(|XMLHttpRequest|navigator\.sendBeacon",
                         text):
        problems.append(f"external request: {text[m.start():m.end() + 60]!r}")
    return problems


def main() -> int:
    problems = check_page(PAGE.read_text(encoding="utf-8"))
    for p in problems:
        print(f"PROBLEM: {p}", file=sys.stderr)
    print(f"{PAGE.relative_to(REPO)}: " + ("consistent with the report and the deck" if not problems
                                          else f"{len(problems)} problem(s)"))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
